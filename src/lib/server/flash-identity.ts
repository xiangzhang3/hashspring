/** Preserve historical worker URLs; keep full IDs for CMS records. */
export function generateSeoSlug(title: string, hashId: string): string {
  if (hashId.startsWith('admin_')) return hashId;
  const slug = title.toLowerCase().replace(/\$([a-z0-9]+)/g, '$1')
    .replace(/[^a-z0-9\s-]/g, '').replace(/\s+/g, '-')
    .replace(/-+/g, '-').replace(/^-|-$/g, '').slice(0, 60);
  const shortHash = hashId.replace(/^h/, '').slice(0, 8);
  return slug ? `${slug}-${shortHash}` : hashId;
}

export function flashLookupFilter(id: string): Record<string, string> {
  // Only permit the identifier grammar generated by this application, not PostgREST operators.
  if (!/^[a-zA-Z0-9_-]{1,200}$/.test(id)) return { content_hash: 'eq.__invalid__' };
  if (id.startsWith('admin_') || !/-[a-z0-9]{4,10}$/.test(id)) return { content_hash: `eq.${id}` };
  const suffix = id.match(/-([a-z0-9]{4,10})$/)![1];
  return { or: `(content_hash.eq.${id},content_hash.like.*${suffix})` };
}
